#include "Vehicle/OffroadCar/Team24OffroadWheelFront.h"

UTeam24OffroadWheelFront::UTeam24OffroadWheelFront()
{
	// ===========================================================================
    // [타이어 규격 및 구동]
    // ===========================================================================

	WheelRadius = 50.0f;
    // 바퀴의 반지름을 설정.
    // 바퀴가 커야 산길의 큰 돌멩이나 웅덩이를 만나도 바퀴가 빠지지 않고 타고 넘을 수 있습니다.

	bAffectedByEngine = true;
    // 엔진의 힘이 이 앞바퀴에도 전달되도록 켭니다.(중요)
    // 일반적인 차는 뒷바퀴만 굴러서 앞으로 가지만(후륜구동),
    // 옵션을 켜면 앞바퀴도 같이 굴러가면서 땅을 파헤칩니다. 즉, 험지 돌파를 가능하게 하는 사륜구동(4WD / AWD) 자동차가 완성되는 부분입니다.


    // ===========================================================================
    // [마찰력 및 코너링]
    // ===========================================================================

	CorneringStiffness = 750.0f;
    // 코너를 돌 때 타이어가 옆으로 밀리지 버티는 힘입니다.

	FrictionForceMultiplier = 4.0f;
    // 타이어의 접지력(마찰력)을 4.0배로 설정합니다.
    // 진흙탕이나 모래밭에서는 바퀴가 쉽게 헛돕니다.
    // 산비탈을 오를 때 타이어가 미끄러지지 않고 땅을 올라갈 수 있도록 접지력을 높게 설정했습니다.


    // ===========================================================================
    // [3. 서스펜션 (Suspension) - 길고 부드러운 하체]
    // ===========================================================================

	SuspensionMaxRaise = 20.0f;
	SuspensionMaxDrop = 20.0f;
    // 기능: 바퀴가 위아래로 움직일 수 있는 최대 거리(가동 범위)를 20cm로 아주 길게 줍니다.
    // 초보자 가이드: 스포츠카(5cm)의 4배입니다! 바닥에 큰 바위가 있어도 바퀴만 쑥 올라가고 차체는 수평을 유지할 수 있게 해주는 '긴 다리' 역할을 합니다.

	WheelLoadRatio = 1.0f;
    // 차체의 무게를 바퀴가 나눠 가지는 비율입니다.

	SpringRate = 100.0f;
    // 스프링의 단단한 정도입니다. 수치가 100으로 '부드럽게' 설정되었습니다.
    // 스포츠카(500)처럼 단단하면 돌멩이를 밟을 때마다 차 전체가 덜컹거립니다.
    // 100 정도로 낮게 세팅해야, 거친 산길의 충격을 스프링이 흡수해서 차체가 안정적으로 유지됩니다.

	SpringPreload = 100.0f;
    // 스프링이 차체 무게를 버티기 위해 지탱하고 있는 기본 힘입니다.

	SweepShape = ESweepShape::Shapecast;
    // 바퀴가 땅에 닿았는지 검사할 때, 점(Ray) 하나가 아니라 실제 타이어 모양(Shapecast)을 기준으로 입체적으로 훑으며 계산합니다.
    // 울퉁불퉁한 오프로드 지형에서 필수적인 옵션입니다.


	// Shapecast 사용이유
	/*
	   Raycast(선 검사)
	   일반적인 자동차 게임은 컴퓨터 연산을 줄이기 위해, 바퀴 중앙에서 바닥으로 레이저 선 1가닥을 쏴서 땅의 높이를 잽니다.
	   평탄한 길에서는 문제가 없지만, 오프로드의 바위 틈새나 폴리곤이 깨진 틈 위를 지날 때 레이전 선이 바위 틈새로 빠져버리는 경우가 발생합니다.
	   그러면 물리 엔진은 바퀴 전체가 구덩이에 빠졌다라고 인지해서 차를 땅으로 푹 꺼지게 만들거나, 제자리에 끼어버리게 만듭니다

	   Shapecast(도형 검사)
	   이 옵션을 켜면 레이저 선 대신 타이어 모양의 보이지 않는 원통을 굴려서 바닥 지형을 검사합니다.
	   타이어의 닿는 면적이 넓기 때문에, 좁은 바위 틈새나 작은 웅덩이 위를 지날 때 틈새로 빠지지 않고 양옆의 높은 돌멩이에 걸쳐져 자연스럽게 건너듯 타고 넘어가게 됩니다.
	*/

    // ===========================================================================
    // [제동 (Brake)]
    // ===========================================================================

	MaxBrakeTorque = 3000.0f;
    // 브레이크의 제동력입니다. 스포츠카(4500)보다 약하게 세팅했습니다.


	// 약하게 세팅 이유
	/*
	아스팔트가 아닌 흙길이나 눈길에서 브레이크를 스포츠카처럼 너무 세게(4500.0f) 잡아버리면,
	타이어가 천천히 도는 게 아니라 회전을 완전히 멈추고 제자리에 굳어버립니다.
	바퀴는 멈췄는데 차의 무거운 몸통은 관성 때문에 앞으로 계속 나아가려고 합니다.
	결국 타이어는 굴러가지 못하고 미끄러지는 현상이 생깁니다.
	이렇게 미끄러지기 시작하면 멈추는 데 걸리는 제동 거리가 오히려 길어지고, 핸들을 꺾어도 차가 말을 듣지 않고 그대로 직진합니다.

	약한 브레이크가 더 잘 멈추는 이유
	브레이크 힘을 낮게 설정하면 제동을 걸어도 바퀴가 완전히 굳지 않고 천천히 굴러가게 되서 안정적이게 멈춥니다.
    */

	MaxHandBrakeTorque = 6000.0f;
    // 사이드 브레이크 제동력입니다.
    // 비상시 바퀴를 잠글 수 있습니다.
}
